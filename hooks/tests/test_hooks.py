"""Tests for the kit's hooks.

Run: python3 -m unittest discover -s hooks/tests -v

Each hook test builds a throwaway project with its own
`.claude/agent-workflow.json`, pipes a tool-call payload into the hook script
exactly as Claude Code would, and checks the exit code and output. Fixtures
cover two unrelated stacks (Flutter and Go) to prove the hooks carry no
stack knowledge of their own.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

HOOKS_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(HOOKS_DIR))

from workflow_config import matches  # noqa: E402

FLUTTER_CONFIG = {
    "protected": [
        {"glob": "**/*.g.dart", "reason": "Generated. Edit the source and run build_runner."},
        {"glob": "**/*.freezed.dart", "reason": "Generated. Edit the source and run build_runner."},
    ],
    "pairedFiles": [
        {"glob": "lib/l10n/app_*.arb", "reminder": "Update all 8 ARB files together."},
    ],
}

GO_CONFIG = {
    "protected": [
        {"glob": "db/migrations/**", "reason": "Applied migrations are immutable.", "allowCreate": True},
        {"glob": "**/*.pb.go", "reason": "Generated by protoc."},
    ],
}


class Project:
    """A temporary project directory with an optional workflow config."""

    def __init__(self, config: dict | None = None, raw_config: str | None = None):
        self._tmp = tempfile.TemporaryDirectory()
        self.root = Path(self._tmp.name).resolve()
        if config is not None or raw_config is not None:
            (self.root / ".claude").mkdir()
            text = raw_config if raw_config is not None else json.dumps(config)
            (self.root / ".claude" / "agent-workflow.json").write_text(text)

    def write(self, relative: str, content: str = "") -> Path:
        path = self.root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        return path

    def run(self, hook: str, file_path: str | None, stdin: str | None = None, tool_name: str = "Edit", **tool_input):
        if stdin is None:
            if file_path is not None:
                tool_input["file_path"] = file_path
            stdin = json.dumps({"tool_name": tool_name, "tool_input": tool_input, "cwd": str(self.root)})
        env = {**os.environ, "CLAUDE_PROJECT_DIR": str(self.root)}
        return subprocess.run(
            [sys.executable, str(HOOKS_DIR / hook)],
            input=stdin,
            capture_output=True,
            text=True,
            env=env,
            cwd=self.root,
        )

    def cleanup(self):
        self._tmp.cleanup()


def context_of(result) -> str:
    """The additionalContext a PostToolUse hook handed to Claude ('' if none)."""
    if not result.stdout.strip():
        return ""
    output = json.loads(result.stdout)
    assert output["hookSpecificOutput"]["hookEventName"] == "PostToolUse"
    return output["hookSpecificOutput"]["additionalContext"]


class GlobTest(unittest.TestCase):
    def test_double_star_slash_matches_root_and_nested(self):
        self.assertTrue(matches("a.g.dart", "**/*.g.dart"))
        self.assertTrue(matches("lib/models/a.g.dart", "**/*.g.dart"))
        self.assertFalse(matches("lib/models/a.dart", "**/*.g.dart"))

    def test_single_star_does_not_cross_directories(self):
        self.assertTrue(matches("lib/l10n/app_en.arb", "lib/l10n/app_*.arb"))
        self.assertFalse(matches("lib/l10n/old/app_en.arb", "lib/l10n/app_*.arb"))

    def test_trailing_double_star_matches_everything_below(self):
        self.assertTrue(matches("db/migrations/0001_init.sql", "db/migrations/**"))
        self.assertTrue(matches("db/migrations/2026/0002.sql", "db/migrations/**"))
        self.assertFalse(matches("db/seed.sql", "db/migrations/**"))

    def test_question_mark_and_regex_characters(self):
        self.assertTrue(matches("v1.txt", "v?.txt"))
        self.assertFalse(matches("v10.txt", "v?.txt"))
        self.assertTrue(matches("a+b(1).txt", "a+b(1).txt"))
        self.assertFalse(matches("aab1.txt", "a+b(1).txt"))

    def test_patterns_are_anchored(self):
        self.assertFalse(matches("src/lib/l10n/app_en.arb", "lib/l10n/app_*.arb"))
        self.assertFalse(matches("a.g.dart.bak", "**/*.g.dart"))


class PreEditTest(unittest.TestCase):
    def tearDown(self):
        self.project.cleanup()

    def test_no_config_allows_everything(self):
        self.project = Project()
        path = self.project.write("lib/a.g.dart")
        self.assertEqual(self.project.run("pre_edit.py", str(path)).returncode, 0)

    def test_unreadable_config_never_blocks(self):
        self.project = Project(raw_config="{ not json")
        path = self.project.write("lib/a.g.dart")
        result = self.project.run("pre_edit.py", str(path))
        self.assertEqual(result.returncode, 0)
        self.assertIn("ignoring unreadable", result.stderr)

    def test_blocks_existing_generated_file_with_reason_for_claude(self):
        self.project = Project(FLUTTER_CONFIG)
        path = self.project.write("lib/models/recipe.g.dart")
        result = self.project.run("pre_edit.py", str(path))
        self.assertEqual(result.returncode, 2)
        self.assertIn("lib/models/recipe.g.dart is protected", result.stderr)
        self.assertIn("run build_runner", result.stderr)

    def test_blocks_creating_generated_file_by_hand(self):
        self.project = Project(FLUTTER_CONFIG)
        result = self.project.run("pre_edit.py", str(self.project.root / "lib/new.freezed.dart"))
        self.assertEqual(result.returncode, 2)

    def test_allows_source_files(self):
        self.project = Project(FLUTTER_CONFIG)
        path = self.project.write("lib/models/recipe.dart")
        self.assertEqual(self.project.run("pre_edit.py", str(path)).returncode, 0)

    def test_allow_create_permits_new_migration_but_not_edits(self):
        self.project = Project(GO_CONFIG)
        existing = self.project.write("db/migrations/0001_init.sql", "create table t();")
        self.assertEqual(self.project.run("pre_edit.py", str(existing)).returncode, 2)
        new = self.project.root / "db/migrations/0002_add_column.sql"
        self.assertEqual(self.project.run("pre_edit.py", str(new)).returncode, 0)

    def test_relative_paths_resolve_against_project_root(self):
        self.project = Project(GO_CONFIG)
        self.project.write("api/v1/user.pb.go")
        self.assertEqual(self.project.run("pre_edit.py", "api/v1/user.pb.go").returncode, 2)

    def test_files_outside_the_project_are_ignored(self):
        self.project = Project(FLUTTER_CONFIG)
        with tempfile.TemporaryDirectory() as other:
            outside = Path(other) / "x.g.dart"
            outside.write_text("")
            self.assertEqual(self.project.run("pre_edit.py", str(outside)).returncode, 0)

    def test_notebook_path_is_checked(self):
        self.project = Project({"protected": [{"glob": "notebooks/**", "reason": "Read-only."}]})
        path = self.project.write("notebooks/a.ipynb", "{}")
        stdin = json.dumps({"tool_name": "NotebookEdit", "tool_input": {"notebook_path": str(path)}})
        self.assertEqual(self.project.run("pre_edit.py", None, stdin=stdin).returncode, 2)

    def test_garbage_or_empty_payload_is_ignored(self):
        self.project = Project(FLUTTER_CONFIG)
        self.assertEqual(self.project.run("pre_edit.py", None, stdin="not json").returncode, 0)
        self.assertEqual(self.project.run("pre_edit.py", None, stdin="").returncode, 0)


class PostEditTest(unittest.TestCase):
    def tearDown(self):
        self.project.cleanup()

    def test_no_config_is_silent(self):
        self.project = Project()
        path = self.project.write("lib/l10n/app_en.arb", "{}")
        result = self.project.run("post_edit.py", str(path))
        self.assertEqual((result.returncode, result.stdout), (0, ""))

    def test_paired_file_reminder_reaches_claude_as_context(self):
        self.project = Project(FLUTTER_CONFIG)
        path = self.project.write("lib/l10n/app_de.arb", "{}")
        result = self.project.run("post_edit.py", str(path))
        self.assertEqual(result.returncode, 0)
        self.assertEqual(context_of(result), "Update all 8 ARB files together.")

    def test_unrelated_file_is_silent(self):
        self.project = Project(FLUTTER_CONFIG)
        path = self.project.write("lib/main.dart")
        self.assertEqual(context_of(self.project.run("post_edit.py", str(path))), "")

    def test_change_plan_without_status_gets_a_reminder(self):
        self.project = Project(FLUTTER_CONFIG)
        path = self.project.write("docs/changes/2026-10-22-csv-export/plan.md", "# feat: x\n\n- [ ] Task\n")
        self.assertIn("has no status line", context_of(self.project.run("post_edit.py", str(path))))

    def test_change_brief_with_status_is_silent(self):
        self.project = Project(FLUTTER_CONFIG)
        path = self.project.write(
            "docs/changes/2026-10-22-csv-export/brief.md",
            "---\ncreated: 2026-10-22\n---\n\n# CSV export\n\n> **Status:** prepped — no recipe yet.\n",
        )
        self.assertEqual(context_of(self.project.run("post_edit.py", str(path))), "")

    def test_only_briefs_and_plans_in_change_folders_need_a_status(self):
        self.project = Project(GO_CONFIG)
        plan = self.project.write("docs/changes/2026-10-22-retry-payouts/plan.md", "# fix: y\n")
        self.assertIn("has no status line", context_of(self.project.run("post_edit.py", str(plan))))
        for exempt in (
            "docs/changes/README.md",
            "docs/changes/2026-10-22-retry-payouts/notes.md",
            "docs/changes/.tasting/rules-reviewer.md",
            "docs/changes/2026-10-22-retry-payouts/sub/plan.md",
            "planning/2026-10-22-other/plan.md",
        ):
            path = self.project.write(exempt, "# no status\n")
            self.assertEqual(context_of(self.project.run("post_edit.py", str(path))), "", exempt)

    def test_formatter_runs_on_the_edited_file_quietly(self):
        formatter = f"{sys.executable} -c \"import sys; open(sys.argv[1], 'w').write('formatted')\" {{file}}"
        self.project = Project({"formatOnEdit": [{"glob": "**/*.go", "command": formatter}]})
        path = self.project.write("my dir/a b.go", "package main")
        result = self.project.run("post_edit.py", str(path))
        self.assertEqual(context_of(result), "")
        self.assertEqual(path.read_text(), "formatted")

    def test_formatter_failure_is_reported_not_blocking(self):
        failing = f"{sys.executable} -c \"import sys; sys.exit('syntax error at 3:1')\" {{file}}"
        self.project = Project({"formatOnEdit": [{"glob": "**/*.go", "command": failing}]})
        path = self.project.write("main.go", "package main")
        result = self.project.run("post_edit.py", str(path))
        self.assertEqual(result.returncode, 0)
        self.assertIn("syntax error at 3:1", context_of(result))

    def test_missing_formatter_and_missing_placeholder_are_explained(self):
        self.project = Project(
            {
                "formatOnEdit": [
                    {"glob": "*.kt", "command": "definitely-not-installed-fmt {file}"},
                    {"glob": "*.go", "command": "gofmt -w"},
                ]
            }
        )
        kotlin = self.project.write("App.kt")
        self.assertIn("is not installed", context_of(self.project.run("post_edit.py", str(kotlin))))
        go = self.project.write("main.go")
        self.assertIn("no {file} placeholder", context_of(self.project.run("post_edit.py", str(go))))

    PATTERNS = {
        "patterns": [
            {"glob": "lib/**/*.dart", "regex": r"Widget\s+_build\w*\(", "message": "Extract a StatelessWidget."},
            {"glob": "lib/pages/**/*.dart", "regex": r"Color\(0x", "message": "Use a design-system color token."},
        ]
    }

    def test_pattern_in_added_text_is_flagged(self):
        self.project = Project(self.PATTERNS)
        path = self.project.write("lib/pages/home_page.dart", "class Home {}\n")
        result = self.project.run(
            "post_edit.py", str(path), old_string="class Home {}", new_string="  Widget _buildHeader() => const Text('x');"
        )
        self.assertIn("`Widget _buildHeader(` — Extract a StatelessWidget.", context_of(result))

    def test_patterns_check_writes_and_every_multiedit(self):
        self.project = Project(self.PATTERNS)
        page = self.project.write("lib/pages/a_page.dart", "x")
        written = self.project.run("post_edit.py", str(page), tool_name="Write", content="final c = Color(0xFF000000);")
        self.assertIn("Use a design-system color token.", context_of(written))
        multi = self.project.run(
            "post_edit.py", str(page), tool_name="MultiEdit",
            edits=[{"old_string": "a", "new_string": "b"}, {"old_string": "c", "new_string": "Widget _buildRow() {"}],
        )
        self.assertIn("Extract a StatelessWidget.", context_of(multi))

    def test_existing_violations_and_other_folders_stay_quiet(self):
        self.project = Project(self.PATTERNS)
        legacy = self.project.write("lib/pages/old_page.dart", "Widget _buildLegacy() {}\nfinal a = 1;\n")
        self.assertEqual(
            context_of(self.project.run("post_edit.py", str(legacy), old_string="final a = 1;", new_string="final a = 2;")), ""
        )
        token_file = self.project.write("lib/design_system/app_colors.dart", "x")
        self.assertEqual(
            context_of(self.project.run("post_edit.py", str(token_file), new_string="const accent = Color(0xFFAA5533);")), ""
        )

    def test_invalid_pattern_is_explained_not_fatal(self):
        self.project = Project({"patterns": [{"glob": "**/*.go", "regex": "fmt.Println(", "message": "x"}]})
        path = self.project.write("main.go", "package main")
        result = self.project.run("post_edit.py", str(path), new_string="fmt.Println(1)")
        self.assertEqual(result.returncode, 0)
        self.assertIn("is not a valid regex", context_of(result))

    def test_several_messages_arrive_together(self):
        config = {
            "formatOnEdit": [{"glob": "docs/**", "command": "definitely-not-installed-fmt {file}"}],
            "pairedFiles": [{"glob": "docs/changes/*/plan.md", "reminder": "Tick finished boxes."}],
        }
        self.project = Project(config)
        path = self.project.write("docs/changes/2026-10-22-z/plan.md", "# z\n")
        context = context_of(self.project.run("post_edit.py", str(path)))
        for expected in ("is not installed", "Tick finished boxes.", "has no status line"):
            self.assertIn(expected, context)


